"""
パラメータの詳細説明:

min_match_count:
    ロゴ検出に必要な最小マッチ数。
    大きくすると誤検出が減るが検出漏れが増える。
    小さくすると検出感度が上がるが誤検出も増える。
    推奨値: 8-15

max_workers:
    並列処理の最大ワーカー数。
    多いとCPU使用率が上がり処理が早くなるが、メモリ使用量も増加する。
    推奨値: CPUコア数に合わせて3-8

feature_matcher.match_threshold:
    特徴点マッチングの品質閾値 (Lowe's ratio test)。
    小さくするとマッチングの精度が上がるが、有効なマッチ数が減少する。
    0.6-0.8が一般的、低いほど厳格。

feature_matcher.trees:
    FLANNマッチャーのインデックスツリー数。
    多いほど検索精度が上がるが、メモリ使用量とインデックス構築時間が増加する。
    少ないとインデックス構築は速いが、マッチング精度が低下する可能性がある。
    推奨値: 4-16（大きなデータセットでは多く設定）

feature_matcher.checks:
    FLANNマッチャーの探索チェック回数。
    多いほど正確なマッチングができるが処理時間が増加する。
    少ないと高速だが、最適でないマッチングが増える可能性がある。
    推奨値: 32-100（精度重視なら多く、速度重視なら少なく）

clustering.eps:
    DBSCANのクラスタ半径（ピクセル単位）。
    大きいとより広範囲の特徴点をグループ化できるが、
    異なるロゴが1つのクラスタになる可能性がある。
    小さすぎるとクラスタが細かく分割されすぎる。
    画像サイズに依存するため、解像度に応じて調整が必要。
    推奨値: 画像の小さい方の辺の長さの約5%

clustering.min_samples:
    DBSCANのクラスタを形成する最小点数。
    大きいとノイズに強くなるが、小さなロゴや特徴点が少ないロゴが検出されにくくなる。
    小さいと検出感度が上がるがノイズも拾いやすくなる。
    推奨値: 3-5（少ない特徴点でもロゴを検出したい場合は小さく）

position.position_threshold:
    中央判定の閾値。
    この値より小さい相対距離なら「中央」と判定される。
    大きいと「中央」判定の範囲が広がる。
    0.33は画面を9分割したときの中央エリアに相当する。
    推奨値: 0.25-0.4

text_detection.min_confidence:
    テキスト検出の最小信頼度。
    低いと多くのテキスト候補を検出するが誤検出も増える。
    高いと確実なテキストのみ検出するが検出漏れも増える。
    画像の品質やテキストのコントラストに応じて調整が必要。
    推奨値: 0.4-0.7

text_detection.min_size:
    テキスト検出のための最小画像サイズ。
    大きいほど精度が上がるが処理時間とメモリ使用量が増加する。
    小さな画像は自動的にこのサイズにリサイズされる。
    小さすぎると細かいテキストが検出できなくなる。
    推奨値: 320-640

text_detection.similarity_threshold:
    テキスト類似度の閾値。
    テキストマッチングの最小一致度。
    低いとより柔軟なマッチングが可能だが誤検出が増える。
    高いとより厳密なマッチングになるが検出漏れが増える。
    OCRの精度やテキストの複雑さに応じて調整する。
    推奨値: 0.5-0.8
"""
